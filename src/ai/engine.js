/**
 * PromptForge Multi-Model AI Dispatcher
 */

import { getSystemPrompt, offlineTransform } from './prompts.js';

export async function dispatchPromptRefinement({ rawThought, framework = 'balanced', settings }) {
  const provider = settings?.provider || 'offline';
  const systemPrompt = getSystemPrompt(framework);

  if (!rawThought || !rawThought.trim()) {
    throw new Error('Please enter a thought, question, or task to forge.');
  }

  // 1. Offline Mode (Zero setup, 100% private)
  if (provider === 'offline') {
    return offlineTransform(rawThought, framework);
  }

  // 2. Chrome Built-in AI (Prompt API / Gemini Nano on-device)
  if (provider === 'chrome_ai') {
    return await callChromeBuiltinAI(rawThought, systemPrompt);
  }

  // 3. Google Gemini API
  if (provider === 'gemini') {
    if (!settings.geminiApiKey) {
      throw new Error('Gemini API key is missing. Add it in Options or switch to Offline mode.');
    }
    return await callGeminiAPI(rawThought, systemPrompt, settings.geminiApiKey);
  }

  // 4. OpenAI API
  if (provider === 'openai') {
    if (!settings.openaiApiKey) {
      throw new Error('OpenAI API key is missing. Add it in Options or switch to Offline mode.');
    }
    return await callOpenAICompatibleAPI({
      endpoint: 'https://api.openai.com/v1/chat/completions',
      apiKey: settings.openaiApiKey,
      model: 'gpt-4o-mini',
      rawThought,
      systemPrompt
    });
  }

  // 5. Anthropic Claude API
  if (provider === 'anthropic') {
    if (!settings.anthropicApiKey) {
      throw new Error('Anthropic API key is missing. Add it in Options or switch to Offline mode.');
    }
    return await callAnthropicAPI(rawThought, systemPrompt, settings.anthropicApiKey);
  }

  // 6. Groq High-Speed API
  if (provider === 'groq') {
    if (!settings.groqApiKey) {
      throw new Error('Groq API key is missing. Add it in Options or switch to Offline mode.');
    }
    return await callOpenAICompatibleAPI({
      endpoint: 'https://api.groq.com/openai/v1/chat/completions',
      apiKey: settings.groqApiKey,
      model: 'llama-3.3-70b-versatile',
      rawThought,
      systemPrompt
    });
  }

  // 7. DeepSeek API
  if (provider === 'deepseek') {
    if (!settings.deepseekApiKey) {
      throw new Error('DeepSeek API key is missing. Add it in Options or switch to Offline mode.');
    }
    return await callOpenAICompatibleAPI({
      endpoint: 'https://api.deepseek.com/chat/completions',
      apiKey: settings.deepseekApiKey,
      model: 'deepseek-chat',
      rawThought,
      systemPrompt
    });
  }

  // 8. Ollama Localhost
  if (provider === 'ollama') {
    const endpoint = settings.ollamaEndpoint || 'http://localhost:11434/api/generate';
    const model = settings.ollamaModel || 'llama3';
    return await callOllama(rawThought, systemPrompt, endpoint, model);
  }

  // Fallback
  return offlineTransform(rawThought, framework);
}

/**
 * Chrome Built-in AI (window.ai)
 */
async function callChromeBuiltinAI(rawThought, systemPrompt) {
  const ai = globalThis.ai || (typeof window !== 'undefined' && window.ai);
  if (!ai || !ai.languageModel) {
    throw new Error('Chrome Built-in AI is not available in this browser. Try Gemini, OpenAI, or Offline mode.');
  }

  const capabilities = await ai.languageModel.capabilities();
  if (capabilities.available === 'no') {
    throw new Error('Chrome Built-in AI is currently unavailable on this device.');
  }

  const session = await ai.languageModel.create({ systemPrompt });
  const response = await session.prompt(rawThought);
  session.destroy();
  return response.trim();
}

/**
 * Google Gemini API
 */
async function callGeminiAPI(rawThought, systemPrompt, apiKey) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;

  const payload = {
    system_instruction: { parts: [{ text: systemPrompt }] },
    contents: [
      {
        parts: [{ text: `Human's rough thought:\n"${rawThought}"\n\nForge the optimal prompt now:` }]
      }
    ],
    generationConfig: {
      temperature: 0.35,
      maxOutputTokens: 1024
    }
  };

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload)
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err?.error?.message || `Gemini API error (Status ${res.status})`);
  }

  const data = await res.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) throw new Error('No prompt generated by Gemini API.');
  return text.trim();
}

/**
 * Anthropic Claude Messages API
 */
async function callAnthropicAPI(rawThought, systemPrompt, apiKey) {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
      'dangerously-allow-browser': 'true'
    },
    body: JSON.stringify({
      model: 'claude-3-5-haiku-20241022',
      max_tokens: 1024,
      system: systemPrompt,
      messages: [
        { role: 'user', content: `Human's rough thought:\n"${rawThought}"\n\nForge the optimal prompt now:` }
      ]
    })
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err?.error?.message || `Anthropic API error (${res.status})`);
  }

  const data = await res.json();
  const text = data.content?.[0]?.text;
  if (!text) throw new Error('No content returned from Claude API.');
  return text.trim();
}

/**
 * OpenAI-Compatible endpoint (OpenAI, Groq, DeepSeek)
 */
async function callOpenAICompatibleAPI({ endpoint, apiKey, model, rawThought, systemPrompt }) {
  const res = await fetch(endpoint, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model,
      temperature: 0.35,
      messages: [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: `Human's rough thought:\n"${rawThought}"\n\nForge the optimal prompt now:` }
      ]
    })
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err?.error?.message || `API error (${res.status})`);
  }

  const data = await res.json();
  const text = data.choices?.[0]?.message?.content;
  if (!text) throw new Error('No content returned from AI provider.');
  return text.trim();
}

/**
 * Localhost Ollama API
 */
async function callOllama(rawThought, systemPrompt, endpoint, model) {
  const res = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model,
      system: systemPrompt,
      prompt: `Human's rough thought:\n"${rawThought}"\n\nForge the optimal prompt now:`,
      stream: false
    })
  });

  if (!res.ok) {
    throw new Error(`Failed to connect to Ollama at ${endpoint}. Please ensure Ollama is running.`);
  }

  const data = await res.json();
  return (data.response || '').trim();
}
